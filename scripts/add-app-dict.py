import re, io, os

for loc, block in APP_DICTS.items():
    p = f"src/lib/i18n/{loc}.ts"
    src = open(p, encoding="utf-8").read()

    # 1) nav.androidApp after nav.categories
    if "androidApp" not in src:
        m = re.search(r'(    categories: "[^"]*",\n)', src)
        if not m:
            print(f"FAIL nav anchor {loc}"); continue
        src = src[:m.end(1)] + f'    androidApp: "{NAV_ANDROID[loc]}",\n' + src[m.end(1):]

    # 2) app dict after the legal block closing "  },\n" that precedes "  chat: {"
    if "\n  app: {" not in src:
        m = re.search(r'(\n  chat: \{)', src)
        if not m:
            print(f"FAIL chat anchor {loc}"); continue
        src = src[:m.start(1)] + "\n" + block + src[m.start(1):]

    open(p, "w", encoding="utf-8").write(src)
    print(f"OK {loc}")
