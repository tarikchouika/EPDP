#!/usr/bin/env python3
"""Apply fetched real-world templates + provenance into the platform data layer.

Reads  scripts/real-forms/fetched/*.json  ({id, source, url, lang, text})
and     scripts/real-forms/sources-only.json  (provenance links without text)
then generates:
  • src/lib/data/real-templates.ts  (verified texts overriding base templates)
  • src/lib/data/real-sources.ts    (provenance map shown in the UI badge)

Also prints coverage measurement (docs with real text / templated docs / all docs).

Run: python3 scripts/real-forms/apply.py
"""
import json, glob, os, datetime

BASE = os.path.dirname(os.path.abspath(__file__))
ROOT = f"{BASE}/../.."

def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")

def main():
    fetched = []
    for p in sorted(glob.glob(f"{BASE}/fetched/*.json")):
        fetched.append(json.load(open(p, encoding="utf-8")))

    sources_only = {}
    so_path = f"{BASE}/sources-only.json"
    if os.path.exists(so_path):
        sources_only = json.load(open(so_path, encoding="utf-8"))

    catalog = {d["id"]: d for d in json.load(open(f"{BASE}/catalog.json", encoding="utf-8"))}
    today = datetime.date.today().isoformat()

    templates, sources = {}, {}
    for f in fetched:
        did = f["id"]
        if did not in catalog:
            print(f"  ! unknown doc id {did} — skipped")
            continue
        entry = templates.setdefault(did, {})
        entry[f["lang"]] = f["text"]
        sources[did] = {"site": f["source"], "url": f["url"], "verifiedAt": today}

    for did, url in sources_only.items():
        if did in sources:
            continue
        if did not in catalog:
            print(f"  ! unknown doc id {did} (sources-only) — skipped")
            continue
        site = "katib.ma" if "katib.ma" in url else "onebox.ma" if "onebox.ma" in url else "namodaj.ma" if "namodaj.ma" in url else "officiel"
        sources[did] = {"site": site, "url": url, "verifiedAt": today}

    # ── real-templates.ts ──
    tpl_lines = []
    for did, t in sorted(templates.items()):
        ar = t.get("ar")
        fr = t.get("fr")
        parts = []
        if ar: parts.append(f'    ar: `{esc(ar)}`')
        if fr: parts.append(f'    fr: `{esc(fr)}`')
        tpl_lines.append(f'  "{did}": {{\n' + ",\n".join(parts) + ",\n  },")
    tpl_body = "\n".join(tpl_lines)
    tpl_ts = f'''/**
 * Real-world templates fetched from public Moroccan form libraries
 * (katib.ma / onebox.ma / namodaj.ma) — the actual wording used in
 * Moroccan administrative practice, replacing generic placeholder text.
 *
 * GENERATED by scripts/real-forms/apply.py — do not edit by hand.
 * Provenance for each entry lives in real-sources.ts.
 */

import type {{ DocTemplate }} from "./templates";

/** Fetched languages override the base template; the rest falls back to the base. */
export const realTemplates: Record<string, Partial<DocTemplate>> = {{
{tpl_body}
}};
'''
    open(f"{ROOT}/src/lib/data/real-templates.ts", "w", encoding="utf-8").write(tpl_ts)

    # ── real-sources.ts ──
    src_lines = []
    for did, s in sorted(sources.items()):
        src_lines.append(
            f'  "{did}": {{ site: "{s["site"]}", url: "{s["url"]}", verifiedAt: "{s["verifiedAt"]}" }},')
    src_ts = f'''/**
 * Provenance registry — documents whose template text has been verified
 * against a real public source (katib.ma / onebox.ma / namodaj.ma or an
 * official Moroccan administration).
 *
 * GENERATED by scripts/real-forms/apply.py — do not edit by hand.
 * Every entry records where the real-world template lives so users can
 * always cross-check the wording at the source.
 */

export interface RealSource {{
  /** Source site label shown in the UI badge. */
  site: "katib.ma" | "onebox.ma" | "namodaj.ma" | "officiel";
  /** Canonical URL of the real template page. */
  url: string;
  /** ISO date the template was verified against the source. */
  verifiedAt: string;
}}

export const realSources: Record<string, RealSource> = {{
{chr(10).join(src_lines)}
}};
'''
    open(f"{ROOT}/src/lib/data/real-sources.ts", "w", encoding="utf-8").write(src_ts)

    # ── coverage measurement ──
    n_docs = len(catalog)
    n_text = len(templates)
    n_src = len(sources)
    print(f"real texts applied:   {n_text}")
    print(f"provenance links:     {n_src}")
    print(f"templated docs:       {n_docs}")
    print(f"coverage (text):      {n_text}/{n_docs} = {100*n_text//max(n_docs,1)}%")
    print(f"coverage (provenance):{n_src}/{n_docs} = {100*n_src//max(n_docs,1)}%")

if __name__ == "__main__":
    main()
